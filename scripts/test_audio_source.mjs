import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const surahs=JSON.parse(fs.readFileSync(new URL('../data/surahs.json',import.meta.url)));
const source=fs.readFileSync(new URL('../src/audio-source.ts',import.meta.url),'utf8').replace(/^import .*;\n/,'').replaceAll('export ','');
const context=vm.createContext({surahs});
vm.runInContext(ts.transpile(source,{target:ts.ScriptTarget.ES2022}),context);
assert.equal(context.recitationUrl('1:1'),'https://everyayah.com/data/Alafasy_128kbps/001001.mp3');
assert.equal(context.recitationUrl('25:72'),'https://everyayah.com/data/Alafasy_128kbps/025072.mp3');
assert.equal(context.recitationUrl('114:6'),'https://everyayah.com/data/Alafasy_128kbps/114006.mp3');
for(const id of ['0:1','115:1','2:287','1:0','1:1/other','not-an-ayah'])assert.throws(()=>context.recitationUrl(id));
const para=['1:7','2:1','2:2'];
assert.equal(context.adjacentAyah(para,'1:7',1),'2:1','Para playback crosses surah boundaries');
assert.equal(context.adjacentAyah(para,'2:2',1),null,'Playback stops at selected range end');
assert.equal(context.adjacentAyah(para,'1:7',-1),null);
assert.equal(context.adjacentAyah(para,'2:1',-1),'1:7');
assert.equal(context.adjacentAyah(para,'3:1',1),null);
console.log('Audio source and sequence checks passed.');
