import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const surahs=JSON.parse(fs.readFileSync(new URL('../data/surahs.json',import.meta.url)));
const arabicCorpus=JSON.parse(fs.readFileSync(new URL('../data/quran-qpc-hafs.json',import.meta.url)));
const main=fs.readFileSync(new URL('../src/main.tsx',import.meta.url),'utf8');
const helperSource=main.slice(main.indexOf('function readStored('),main.indexOf('function App(){'));
const values=new Map();
const context=vm.createContext({surahs,arabicCorpus,location:{hash:'#1:4'},localStorage:{getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)}});
vm.runInContext(ts.transpile(helperSource,{target:ts.ScriptTarget.ES2022}),context);
assert.equal(context.initialPosition(),'1:4');
values.set('quran-last-read','25:53');
assert.equal(context.initialPosition(),'25:53','Latest reading takes precedence over stale home-screen hash');
values.set('quran-last-read','25:999');
assert.equal(context.initialPosition(),'1:4','Invalid saved ayat falls back safely');
assert.equal(context.loadPlaces().length,5);
values.set('quran-reading-places','{broken');
assert.equal(context.loadPlaces().filter(Boolean).length,0,'Corrupt storage does not crash reader');
const place={name:'Daily reading',ayah:'25:53',view:'para',mode:'translation',language:'urdu',updated:'2026-11-14T00:00:00Z'};
context.writeStored('quran-reading-places',JSON.stringify([place]));
assert.equal(context.loadPlaces()[0].ayah,'25:53');
assert.equal(context.loadPlaces()[0].view,'para');
assert.equal(context.loadPlaces()[0].language,'urdu');
context.writeStored('quran-last-read','2:142');
assert.equal(context.loadPlaces()[0].ayah,'25:53','Changing automatic position cannot overwrite protected places');
assert.equal(context.loadPlaces().length,5,'Exactly five places are available');
values.set('quran-reading-places',JSON.stringify([{...place,ayah:'115:1'}]));
assert.equal(context.loadPlaces()[0],null,'Unknown ayat is rejected');
context.localStorage={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
assert.equal(context.initialPosition(),'1:4','Reader still opens when storage is blocked');
assert.doesNotThrow(()=>context.writeStored('test','value'));
console.log('Reading-state checks passed: stale shortcut, validation, five protected places, preferences, corrupt/blocked storage.');
